#!/usr/bin/env python3
"""Write docs/fonts-embed.js: the shipping TTFs as base64, so the review page
works opened as a plain file (a page cannot fetch a font file from file://)."""
import base64
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_font as BF

ROOT = BF.ROOT
OUT = os.path.join(ROOT, 'docs', 'fonts-embed.js')


def main():
    parts = []
    for key in BF.family_keys():
        f = BF.family(key)
        if os.path.exists(f['ttf']):
            data = base64.b64encode(open(f['ttf'], 'rb').read()).decode()
            parts.append(f'  {key}: "{data}"')
    open(OUT, 'w').write('// generated by fonts/tools/embed_fonts.py; do not edit\nconst FONT_DATA = {\n' + ',\n'.join(parts) + '\n};\n')
    print(f'{os.path.relpath(OUT, ROOT)}: {len(parts)} fonts, {os.path.getsize(OUT) // 1024} KB')
    # cache-bust: the pages reference the fresh data files (a browser otherwise
    # keeps showing an older build of the fonts on the review page)
    import re
    for page, names in (('inspect.html', ('fonts-embed.js', 'fonts-data.js')),):
        path = os.path.join(ROOT, 'docs', page)
        if not os.path.exists(path):
            continue
        html = open(path).read()
        for name in names:
            src = os.path.join(ROOT, 'docs', name)
            if os.path.exists(src):
                ver = int(os.path.getmtime(src))
                html = re.sub(r'src="' + re.escape(name) + r'(\?v=\d+)?"', f'src="{name}?v={ver}"', html)
        open(path, 'w').write(html)
    print('cache-bust: the review page references the fresh font data')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate docs/fonts-data.js — the glyph matrix for the font-study page.

Structure: bases across, derivations down. Every cell is one potential glyph
with its codepoints and how many languages use it (0 = the grammar's reserve,
drawn by the rules but not yet used); combinations the grammar does not define
are empty. Generated from the engine + the mapping.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import engine
from gen_master import aggregate

C_BASES = list('ptkbdgfvszmnlrh')
V_BASES = list('aeiou')

# (ops, label, restricted-to-bases or None)
C_ROWS = [
    ('',   'base',               None),
    ('j',  'soft',               None),
    ('c',  'affricate · tap',    'tdr'),
    ('q',  'hush · uvular',      'tdk'),
    ('x',  'fricative shift',    None),
    ('y',  'back-lean',          None),
    ('jx', 'retroflex hush',     'sz'),
    ('qx', 'retroflex affricate','td'),
    ('yx', 'the special',        None),
    ('cy', 'special affricate',  'td'),
    ('qy', 'special hush',       'td'),
    ('yy', 'special retroflex',  'tdnlr'),
]
V_ROWS = [
    ('',   'base',            None),
    ('c',  'flip',            None),
    ('j',  'lowered',         None),
    ('q',  'c+j',             'eiou'),
    ('q',  'rhotic · vocalic r', 'a'),
    ('y',  'nasal',           None),
    ('w',  'long',            None),
    ('cw', 'long flip',       None),
    ('jw', 'long lowered',    None),
    ('jy', 'nasal lowered',   None),
    ('qw', 'long c+j',        'eiou'),
    ('x',  'glide',           'iu'),
    ('cx', 'flipped glide',   'iu'),
]


def build(bases, rows, langs_of):
    cells = []
    for ops, label, restrict in rows:
        row = {'ops': ops, 'label': label, 'cells': []}
        for b in bases:
            if restrict and b not in restrict:
                row['cells'].append(None)
                continue
            form = b + ops
            try:
                g = engine.glyph(form)
            except engine.ParseError:
                row['cells'].append(None)
                continue
            row['cells'].append({'f': form, 'g': g,
                                 'cps': ' '.join(f'{ord(c):04X}' for c in g),
                                 'langs': langs_of(form)})
        cells.append(row)
    return cells


def main():
    inuse = aggregate()
    langs_of = lambda f: sum(n for n, _ in inuse.get(f, {}).values())
    data = {
        'cons': {'bases': C_BASES, 'rows': build(C_BASES, C_ROWS, langs_of)},
        'vows': {'bases': V_BASES, 'rows': build(V_BASES, V_ROWS, langs_of)},
    }
    out = os.path.join(ROOT, 'docs', 'fonts-data.js')
    with open(out, 'w') as fh:
        fh.write('// generated by scripts/gen_fonts.py — do not edit\n')
        fh.write('const MATRIX = ' + json.dumps(data, ensure_ascii=False) + ';\n')
    n = used = 0
    for sec in data.values():
        for row in sec['rows']:
            for c in row['cells']:
                if c:
                    n += 1
                    used += bool(c['langs'])
    print(f'{out}: {n} glyphs, {used} in use, {n - used} reserve')


if __name__ == '__main__':
    main()

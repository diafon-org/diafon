#!/usr/bin/env python3
"""Generate docs/fonts-data.js — every potential glyph of the system, for the
font-study page.

The structure: one entry per single-segment form the grammar can draw —
everything in use plus the systematic reserve — with its glyph, its
codepoints, and a usage category:
  core        used by 8+ languages
  common      in use by some language
  systematic  grammatical, drawn by the rules, used by no current language
Forms whose glyph would duplicate an earlier one (unused corners like `sy`
vs `sjx`) are dropped; length forms are plain doublings and stay out.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import engine
from gen_master import aggregate

C_BASES = 'ptkbdgfvszmnlrh'
V_BASES = 'aeiou'


def potentials():
    forms = []
    for b in C_BASES:
        forms += [b, b + 'j', b + 'x', b + 'y', b + 'yx']
    for b in 'tdnlr':
        forms.append(b + 'yy')
    forms += ['sjx', 'zjx', 'rc']
    forms += ['tc', 'dc', 'tq', 'dq', 'hq', 'kq',
              'tcy', 'dcy', 'tqx', 'tqy', 'dqx', 'dqy']
    for b in V_BASES:
        forms += [b, b + 'c', b + 'j', b + 'q', b + 'y', b + 'w',
                  b + 'cw', b + 'jw', b + 'jy', b + 'qw']
    forms.remove('aqw')                     # nonsense: aq is a whole glyph
    forms += ['ix', 'ux', 'icx', 'ucx', 'aq']
    return forms


def main():
    inuse = aggregate()
    order = potentials()
    for f in inuse:                      # anything used but not enumerated
        if f not in order and len(engine.tokenize(f)) == 1:
            order.append(f)
    seen_glyphs, entries = {}, []
    for form in order:
        try:
            g = engine.glyph(form)
        except engine.ParseError:
            continue
        if g in seen_glyphs:
            continue
        seen_glyphs[g] = form
        n_langs = sum(n for n, _ in inuse.get(form, {}).values())
        cat = 'core' if n_langs >= 8 else 'common' if n_langs else 'systematic'
        entries.append({'f': form, 'g': g, 'cat': cat,
                        'cps': ' '.join(f'{ord(c):04X}' for c in g),
                        'langs': n_langs})
    out = os.path.join(ROOT, 'docs', 'fonts-data.js')
    with open(out, 'w') as fh:
        fh.write('// generated by scripts/gen_fonts.py — do not edit\n')
        fh.write('const GLYPHS = ' + json.dumps(entries, ensure_ascii=False) + ';\n')
    cats = {c: sum(1 for e in entries if e['cat'] == c)
            for c in ('core', 'common', 'systematic')}
    print(f'{out}: {len(entries)} glyphs {cats}')


if __name__ == '__main__':
    main()

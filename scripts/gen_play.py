#!/usr/bin/env python3
"""Generate docs/play-data.js; the playground's data, from data/*.yaml.

One source of truth: the script rules come from data/script.yaml, the
per-language readings from data/mapping.yaml applied to data/languages/.
The playground's JS engine mirrors scripts/engine.py.
"""
import glob
import json
import os
import sys
import unicodedata as ud

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def nfd(s):
    return ud.normalize('NFD', s)


def main():
    script = yaml.safe_load(open(os.path.join(ROOT, 'data', 'script.yaml')))
    m = yaml.safe_load(open(os.path.join(ROOT, 'data', 'mapping.yaml')))
    cons = {nfd(k): v for k, v in m['consonants'].items()}
    vows = {nfd(k): v for k, v in m['vowels'].items()}
    over = {c: {nfd(k): v for k, v in d.items()} for c, d in m['overrides'].items()}

    langs, default = {}, {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'data', 'languages', '*.yaml'))):
        d = yaml.safe_load(open(path))
        code, native = d['code'], d['speakers']['native']
        readings = {}
        for sec, table in (('consonants', cons), ('vowels', vows)):
            for ipa, freq in d[sec].items():
                if freq == 'X':
                    continue
                key = nfd(ipa)
                form = over.get(code, {}).get(key) or table.get(key)
                if form:
                    readings[form] = ud.normalize('NFC', ipa)
        langs[code] = {'name': d['name'], 'native': native, 'readings': readings}
        for form, ipa in readings.items():
            default.setdefault(form, {}).setdefault(ipa, 0)
            default[form][ipa] += native
    top = {f: max(v.items(), key=lambda kv: kv[1])[0] for f, v in default.items()}

    # the stages and the forms in use, for the engine's reading back
    sys.path.insert(0, os.path.join(ROOT, 'scripts'))
    import stages as stg
    st = {}
    for code in stg.codes():
        d = stg.load(code)
        st[code] = {k: d[k] for k in ('code', 'name', 'long', 'forms', 'caps', 'sample', 'read', 'letters', 'lexical')}
        st[code]['lexicon'] = bool(d.get('lexicon'))       # the tables themselves: docs/lexicon/<code>.json
    data = {'script': script, 'langs': langs, 'default': top, 'stages': st, 'used': sorted(stg.used_forms())}
    out = os.path.join(ROOT, 'docs', 'play-data.js')
    with open(out, 'w') as fh:
        fh.write('// generated by scripts/gen_play.py; do not edit\n')
        fh.write('const DIA = ' + json.dumps(data, ensure_ascii=False) + ';\n')
    print(f'{out}: {len(langs)} languages, {len(top)} forms')


if __name__ == '__main__':
    main()

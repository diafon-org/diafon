#!/usr/bin/env python3
"""Generate the Android input method's data file from docs/spec.json:
input_methods/android/app/src/main/java/io/diafon/ime/SpecData.kt.

The Kotlin engine mirrors scripts/engine.py rule for rule and takes its
tables (script rules, stages) from here, so the IME never carries a hand
copy of any mapping. Run after gen_spec.py; tests/test_kotlin.py replays the
spec vectors through the Kotlin port.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'input_methods', 'android', 'app', 'src', 'main',
                   'java', 'io', 'diafon', 'ime', 'SpecData.kt')


def kstr(s):
    return json.dumps(s, ensure_ascii=False)


def kmap(d):
    return 'mapOf(' + ', '.join(f'{kstr(k)} to {kstr(v)}' for k, v in d.items()) + ')'


def main():
    spec = json.load(open(os.path.join(ROOT, 'docs', 'spec.json')))
    sc = spec['script']
    marks = ',\n        '.join(
        f'{kstr(k)} to Mark({kstr(v.get("below"))}, {kstr(v.get("above"))})'
        for k, v in sc['marks'].items())
    stages = ',\n        '.join(
        f'{kstr(code)} to Stage({kstr(code)}, {kstr(st["name"])}, {kstr(st["long"])}, {kmap(st["forms"])}, {kmap(st.get("caps") or {})}, {kstr(st.get("sample") or "")})'
        for code, st in spec['stages'].items())
    src = f'''// generated by scripts/gen_android.py from docs/spec.json; do not edit
package io.diafon.ime

data class Mark(val below: String?, val above: String?)
data class Stage(val code: String, val name: String, val long: String, val forms: Map<String, String>,
                 val caps: Map<String, String> = emptyMap(), val sample: String = "")

object SpecData {{
    const val GENERATED = {kstr(spec["generated"])}
    const val SOURCE = {kstr(spec["source"] or "")}
    val DESCENDERS: Set<Char> = setOf({', '.join(f"'{c}'" for c in sc['descenders'])})
    val WHOLE: Map<String, String> = {kmap(sc['whole_letters'])}
    val MARKS: Map<String, Mark> = mapOf(
        {marks})
    val PARTNER: Map<Char, Char> = mapOf({', '.join(f"'{k}' to '{v}'" for k, v in sc['flip_partner'].items())})
    val STAGES: Map<String, Stage> = mapOf(
        {stages})
}}
'''
    open(OUT, 'w').write(src)
    print(f'{OUT}: {len(sc["whole_letters"])} whole letters, {len(sc["marks"])} marks, {len(spec["stages"])} stages')


if __name__ == '__main__':
    main()

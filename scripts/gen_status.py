#!/usr/bin/env python3
"""Write docs/status.md: what exists and in what state, read from the data
so the page cannot drift from the repo.

- languages: every data/languages file, its mapping review state
  (data/mapping.yaml `review`), whether it has a spelling stage and its
  state, whether it has a lexicon and its size;
- the tools: the workstream table of plan.md, state column verbatim.
"""
import glob
import json
import os
import re

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'status.md')


def state(s):
    s = (s or 'none').strip()
    key = 'done' if s.startswith('done') else 'native' if s.startswith('native') else \
          'reviewed' if s.startswith('reviewed') else 'draft' if s.startswith('draft') else \
          'open' if s.startswith('open') else 'none' if s == 'none' else 'draft'
    return f'<span class="state {key}">{s}</span>'


def languages():
    mapping = yaml.safe_load(open(os.path.join(ROOT, 'data', 'mapping.yaml')))
    review = mapping.get('review') or {}
    stages = {}
    for fn in glob.glob(os.path.join(ROOT, 'data', 'stages', '*.yaml')):
        d = yaml.safe_load(open(fn))
        stages[d['code']] = d.get('state', 'draft')
    lexica = {}
    for fn in glob.glob(os.path.join(ROOT, 'data', 'lexicon', '*.json')):
        d = json.load(open(fn))
        n = max(len(d.get('read') or {}), len(d.get('write') or {}))
        lexica[d['code']] = (d.get('kind', ''), n)
    rows = []
    for fn in sorted(glob.glob(os.path.join(ROOT, 'data', 'languages', '*.yaml'))):
        d = yaml.safe_load(open(fn))
        code = d['code']
        n_c = sum(1 for v in (d.get('consonants') or {}).values() if v != 'X')
        n_v = sum(1 for v in (d.get('vowels') or {}).values() if v != 'X')
        lex = lexica.get(code)
        rows.append((d['name'], code, (d.get('speakers') or {}).get('native', ''), n_c, n_v,
                     review.get(code, 'not reviewed'), stages.get(code),
                     f'{lex[0]}, {lex[1]:,} entries' if lex else None))
    rows.sort(key=lambda r: -(r[2] or 0))
    out = ['| Language | Speakers (M) | Phonemes | Mapping | Spelling stage | Lexicon |', '|---|---|---|---|---|---|']
    for name, code, sp, nc, nv, rev, st, lex in rows:
        out.append(f'| {name} `{code}` | {sp} | {nc} + {nv} | {state(rev)} | '
                   f'{state(st) if st else state("none")} | {lex or "—"} |')
    n_rev = sum(1 for r in rows if r[5] != 'not reviewed'); n_nat = sum(1 for r in rows if r[5] == 'native')
    summary = (f'{len(rows)} languages carry a phoneme inventory and a mapping; {n_rev} mappings are '
               f'reviewed, {n_nat} of them by a native speaker; {len(stages)} have a spelling stage, '
               f'all drafts pending native review; {len(lexica)} have a lexicon.')
    return summary, '\n'.join(out)


def tools():
    text = open(os.path.join(ROOT, 'plan.md')).read()
    rows = []
    for line in text.split('\n'):
        m = re.match(r'\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|$', line)
        if m:
            rows.append((int(m.group(1)), m.group(2), m.group(4)))
    rows.sort()
    out = ['| Deliverable | State |', '|---|---|']
    for _, what, st in rows:
        out.append(f'| {what} | {state(st)} |')
    return '\n'.join(out)


def main():
    summary, langs = languages()
    md = f'''# Status

*Generated by `scripts/gen_status.py` from the data; edit the data, not this page.*

{summary}

Mapping states: **not reviewed** (the mapping stands as drafted), **reviewed**
(checked against the literature), **native** (checked by a native or expert
reviewer). A spelling stage renders the script in the language's own
orthography; a lexicon adds the word-level knowledge a spelling needs.

## Languages

{langs}

## Tools and deliverables

From the workstream table in `plan.md`.

{tools()}

## The fonts

Three families, Diafon Serif, Sans and Mono, derived from Noto and carrying
every mark. The serif's anchor compositions are being redrawn; the
[font review](inspect.html) page shows the current state glyph by glyph.
'''
    open(OUT, 'w').write(md)
    print(f'{os.path.relpath(OUT, ROOT)}: {summary}')


if __name__ == '__main__':
    main()

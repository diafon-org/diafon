#!/usr/bin/env python3
"""Write the status block of README.md (between the status markers): what
exists and in what state, read from the data so it cannot drift from the
repo.

- the languages in one sentence (the per-language table is on the
  Reference page, scripts/gen_master.py);
- the tools: the workstream table of plan.md, state column verbatim.
"""
import glob
import json
import os
import re

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(ROOT, 'README.md')
MARK0, MARK1 = '<!-- status: generated by scripts/gen_status.py -->', '<!-- /status -->'


def languages():
    review = yaml.safe_load(open(os.path.join(ROOT, 'data', 'mapping.yaml'))).get('review') or {}
    langs = glob.glob(os.path.join(ROOT, 'data', 'languages', '*.yaml'))
    stages = glob.glob(os.path.join(ROOT, 'data', 'stages', '*.yaml'))
    lexica = [json.load(open(fn))['code'] for fn in glob.glob(os.path.join(ROOT, 'data', 'lexicon', '*.json'))]
    n_rev = sum(1 for v in review.values() if v)
    n_nat = sum(1 for v in review.values() if v == 'native')
    return (f'{len(langs)} languages carry a phoneme inventory and a mapping; {n_rev} mappings '
            f'are reviewed, {n_nat} of them by a native speaker; {len(stages)} have a draft '
            f'spelling stage; {len(lexica)} have a lexicon. The Reference page lists every '
            'language with its state.')


def tools():
    rows = []
    for line in open(os.path.join(ROOT, 'plan.md')).read().split('\n'):
        m = re.match(r'\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|$', line)
        if m:
            rows.append((int(m.group(1)), m.group(2), m.group(4)))
    out = ['| Deliverable | State |', '|---|---|']
    out += [f'| {what} | {st} |' for _, what, st in sorted(rows)]
    return '\n'.join(out)


def main():
    block = f'{MARK0}\n{languages()}\n\n{tools()}\n{MARK1}'
    text = open(README).read()
    assert MARK0 in text and MARK1 in text, 'README.md: no status markers'
    text = re.sub(re.escape(MARK0) + '.*?' + re.escape(MARK1), lambda m: block, text, flags=re.S)
    open(README, 'w').write(text)
    print(f'README.md status: {languages()}')


if __name__ == '__main__':
    main()

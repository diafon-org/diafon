#!/usr/bin/env python3
"""Generate the soft keyboards' layout tables from data/layouts.yaml:
input_methods/android/.../Layouts.kt and input_methods/ios/Shared/Layouts.swift.

Every layout must place each of the 26 letters exactly once; a layout that
drops or doubles a letter fails here, before any keyboard is built.
"""
import json
import os
import string

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KT = os.path.join(ROOT, 'input_methods', 'android', 'app', 'src', 'main',
                  'java', 'io', 'diafon', 'ime', 'Layouts.kt')
SWIFT = os.path.join(ROOT, 'input_methods', 'ios', 'Shared', 'Layouts.swift')


def load():
    layouts = yaml.safe_load(open(os.path.join(ROOT, 'data', 'layouts.yaml')))
    for code, lay in layouts.items():
        letters = ''.join(lay['rows'])
        assert sorted(letters) == list(string.ascii_lowercase), f'{code}: {letters} is not the 26 letters once each'
    return layouts


def q(s):
    return json.dumps(s, ensure_ascii=False)


def kotlin(layouts):
    rows = ',\n'.join(
        f'        Triple({q(code)}, {q(lay["label"])}, listOf({", ".join(q(r) for r in lay["rows"])}))'
        for code, lay in layouts.items())
    return f'''// generated by scripts/gen_layouts.py from data/layouts.yaml; do not edit
// The base layouts: where the 26 letters sit. Only placement changes; the
// typing is the same on every layout, since the engine only ever sees letters.
package io.diafon.ime

object Layouts {{
    /** code -> (label, the three letter rows) */
    val ALL: List<Triple<String, String, List<String>>> = listOf(
{rows},
    )

    fun rows(code: String): List<String> = (ALL.firstOrNull {{ it.first == code }} ?: ALL[0]).third

    fun label(code: String): String = (ALL.firstOrNull {{ it.first == code }} ?: ALL[0]).second
}}
'''


def swift(layouts):
    rows = ',\n'.join(
        f'        Layout(code: {q(code)}, label: {q(lay["label"])}, rows: [{", ".join(q(r) for r in lay["rows"])}])'
        for code, lay in layouts.items())
    return f'''// generated by scripts/gen_layouts.py from data/layouts.yaml; do not edit
// The base layouts: where the 26 letters sit. Only placement changes; the
// typing is the same on every layout, since the engine only ever sees letters.

struct Layout {{ let code: String; let label: String; let rows: [String] }}

enum Layouts {{
    static let all: [Layout] = [
{rows}]

    static func get(_ code: String) -> Layout {{ all.first {{ $0.code == code }} ?? all[0] }}
}}
'''


def main():
    layouts = load()
    os.makedirs(os.path.dirname(SWIFT), exist_ok=True)
    open(KT, 'w').write(kotlin(layouts))
    open(SWIFT, 'w').write(swift(layouts))
    print(f'{KT}\n{SWIFT}: {len(layouts)} layouts')


if __name__ == '__main__':
    main()

# The marks the ordinary body font renders badly (below-marks and our custom ones) and the
# precomposed letters that carry them. Prose glyphs are wrapped in the project font by `serif_prose`;
# ordinary European diacritics (á é í ü ö ã …) are deliberately NOT in this set — they render fine
# anywhere, and wrapping them would drop a serif letter into the middle of "Guaraní".
_AWKWARD_MARKS = "\u0313\u0316\u0323\u0324\u0326\u030e\u0330\u0348"
_AWKWARD_PRECOMPOSED = "ṭḍḳṇṛḥẓṣșțạịẹụọġṗ"
_GLYPH_RE = re.compile(f"([A-Za-z'][{_AWKWARD_MARKS}]+|[{_AWKWARD_PRECOMPOSED}][{_AWKWARD_MARKS}]*)")


def serif_prose(html):
    """Set every uni glyph in the PROSE in the project font, not just the ones in tables and tiles.

    The explanations are full of ṭ ḥ h̦ s͈ r̖ — exactly the marks a generic font positions worst, and
    exactly what the page is trying to teach. Wrapping is done here rather than by hand so the prose
    can never drift from the mark set. Text nodes only: never inside a tag, a <script> or a <style>.
    """
    out, i = [], 0
    for m in re.finditer(r"<(script|style)\b.*?</\1>|<[^>]+>", html, re.S):
        out.append(_GLYPH_RE.sub(r'<span class="ug">\1</span>', html[i:m.start()]))
        out.append(m.group(0))
        i = m.end()
    out.append(_GLYPH_RE.sub(r'<span class="ug">\1</span>', html[i:]))
    return "".join(out)


def subset_font_b64(payload, extra=""):
    """Subset the Diaphone font to exactly the codepoints the page can display; return base64 woff2."""
    from fontTools.subset import Subsetter, Options, load_font, save_font
    cps = {ord(c) for c in json.dumps(payload, ensure_ascii=False)} | {ord(c) for c in extra}
    cps |= set(range(0x20, 0x7F))                      # all printable ASCII, for safety
    opts = Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.notdef_glyph = True
    opts.recommended_glyphs = True
    opts.drop_tables += ["Silt"]
    font = load_font(FONT_TTF, opts)
    ss = Subsetter(options=opts)
    ss.populate(unicodes=cps)
    ss.subset(font)
    buf = BytesIO()
    save_font(font, buf, opts)
    return base64.b64encode(buf.getvalue()).decode("ascii"), len(buf.getvalue())


def main():
    payload = build()
    body = serif_prose(PAGE).replace("/*DATA*/", json.dumps(payload, ensure_ascii=False))
    fb64, fsize = subset_font_b64(payload, extra=body)   # prose glyphs count toward the subset too
    html = body.replace("__FONTB64__", fb64)
    out = os.path.join(ROOT, "docs", "index.html")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(html)
    print("wrote", out, "·", payload["counts"], "· font subset", fsize, "bytes")



#!/usr/bin/env python3
"""The site's own words, read once (site/**/*.html after the build, and the page
scripts that write text) -> docs/assets/site-words.js and site/assets/: the
English lexicon's reading of every word the site uses, so the script switch in
the header (assets/site.js) can show the site in Diafon without loading the
whole lexicon. Also the spelling stages the switch offers."""
import glob, html, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import lexicon, stages

WORD = re.compile(r"[A-Za-z][A-Za-z']*[A-Za-z]")       # one letter is a letter named, not a word


def site_text():
    for path in glob.glob(os.path.join(ROOT, 'site', '**', '*.html'), recursive=True):
        s = open(path, encoding='utf-8').read()
        s = re.sub(r'<(script|style|code|pre|svg)\b.*?</\1>', ' ', s, flags=re.S)
        yield html.unescape(re.sub(r'<[^>]+>', ' ', s))
    for path in glob.glob(os.path.join(ROOT, 'docs', 'assets', '*.js')):
        if not path.endswith('site-words.js'):
            yield open(path, encoding='utf-8').read()


def main():
    words = {}
    for text in site_text():
        for w in WORD.findall(text):
            k = w.lower()
            if k not in words:
                t = lexicon.read_word(k, 'en')
                if t is not None:
                    words[k] = t
    spellings = sorted(((c, stages.load(c)['name']) for c in stages.codes() if c not in ('en', 'zh')),
                       key=lambda e: e[1])
    body = ('// generated by scripts/gen_site_words.py: the English reading of every word on the site\n'
            f'const SITE_WORDS = {json.dumps(dict(sorted(words.items())), ensure_ascii=False, separators=(",", ":"))};\n'
            f'const SITE_SPELLINGS = {json.dumps(spellings, ensure_ascii=False)};\n')
    for out in (os.path.join(ROOT, 'docs', 'assets', 'site-words.js'), os.path.join(ROOT, 'site', 'assets', 'site-words.js')):
        if os.path.isdir(os.path.dirname(out)):
            open(out, 'w', encoding='utf-8').write(body)
    print(f'site-words.js: {len(words)} words · {len(body) // 1024} KB')


if __name__ == '__main__':
    main()

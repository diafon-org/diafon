#!/usr/bin/env python3
"""Generate the macOS input method's data file from docs/spec.json:
input_methods/mac/Sources/SpecData.swift.

The Swift engine mirrors scripts/engine.py rule for rule and takes its
tables (script rules, stages, the forms in use) from here, so the input method
never carries a hand copy of any mapping. Run after gen_spec.py;
tests/test_swift.py replays the spec vectors through the Swift port.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'input_methods', 'mac', 'Sources', 'SpecData.swift')


def sstr(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def smap(d):
    return '[' + (', '.join(f'{sstr(k)}: {sstr(v)}' for k, v in d.items()) or ':') + ']'


def main():
    spec = json.load(open(os.path.join(ROOT, 'docs', 'spec.json')))
    sc = spec['script']
    marks = ',\n        '.join(
        f'{sstr(k)}: Mark(below: {sstr(v["below"]) if v.get("below") else "nil"}, above: {sstr(v["above"]) if v.get("above") else "nil"})'
        for k, v in sc['marks'].items())
    stages = ',\n        '.join(
        f'{sstr(code)}: Stage(code: {sstr(code)}, name: {sstr(st["name"])}, long: {sstr(st["long"])}, '
        f'forms: {smap(st["forms"])}, order: [{", ".join(sstr(f) for f in st["forms"])}], '
        f'caps: {smap(st.get("caps") or {})}, read: {smap(st.get("read") or {})}, '
        f'readOrder: [{", ".join(sstr(f) for f in (st.get("read") or {}))}], sample: {sstr(st.get("sample") or "")}, '
        f'lexical: {"true" if st.get("lexical") else "false"}, lexicon: {"true" if st.get("lexicon") else "false"})'
        for code, st in spec['stages'].items())
    used = ', '.join(sstr(f['form']) for f in spec['forms'])
    src = f'''// generated by scripts/gen_mac.py from docs/spec.json; do not edit
import Foundation

struct Mark {{ let below: String?; let above: String? }}
struct Stage {{
    let code: String; let name: String; let long: String
    let forms: [String: String]; let order: [String]           // the spellings, in the stage's order
    let caps: [String: String]
    let read: [String: String]; let readOrder: [String]        // read back only (etymological spellings)
    let sample: String
    let lexical: Bool                                          // no letters of its own (English, Mandarin)
    let lexicon: Bool                                          // a lexicon exists (data/lexicon/<code>.json)
}}

enum SpecData {{
    static let generated = {sstr(spec["generated"])}
    static let source = {sstr(spec["source"] or "")}
    static let descenders: Set<Character> = [{', '.join(sstr(c) for c in sc['descenders'])}]
    static let whole: [String: String] = {smap(sc['whole_letters'])}
    static let marks: [String: Mark] = [
        {marks}]
    static let partner: [Character: Character] = [{', '.join(f'{sstr(k)}: {sstr(v)}' for k, v in sc['flip_partner'].items())}]
    /// the forms the languages use, which decide the reading of a glyph two forms share
    static let used: [String] = [{used}]
    static let stages: [String: Stage] = [
        {stages}]
    /// the stages in the order every screen lists them: by name
    static let stageOrder: [String] = {'[' + ', '.join(sstr(c) for c in sorted(spec['stages'], key=lambda c: spec['stages'][c]['name'])) + ']'}
}}
'''
    open(OUT, 'w').write(src)
    print(f'{OUT}: {len(sc["whole_letters"])} whole letters, {len(sc["marks"])} marks, '
          f'{len(spec["stages"])} stages')


if __name__ == '__main__':
    main()
